"""Build the explicit public offline allowlist. Run after changing public files.

Never include the encrypted archive, Firebase SDKs, account responses or user data.
The revision covers the worker too, so a changed routing policy gets a fresh cache.
"""
from pathlib import Path
import argparse
import hashlib
import json
import re

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'assets/offline-pack.js'


def build():
    games = re.findall(r'\bfile: "([^"]+)"', (ROOT / 'assets/catalog.js').read_text())
    if not games or len(set(games)) != len(games):
        raise ValueError('Expected a nonempty catalog of distinct game files')
    roots = ['index.html', 'gra.html', 'aplikacja.html', 'o-serwisie.html',
             'prywatnosc.html', 'offline.html', 'manifest.webmanifest',
             'gry.html', 'kontakt.html', 'zasady-serwisu.html']
    assets = [p.relative_to(ROOT).as_posix() for p in (ROOT / 'assets').rglob('*')
              if p.is_file() and p != OUTPUT and 'firebase' not in p.name.lower()]
    files = sorted(set(roots + games + assets))
    # Keep the whole catalog readable offline, even before downloading all engines.
    core = roots + [p for p in assets if p.startswith(('assets/fonts/', 'assets/icons/', 'assets/art/'))]
    core += ['assets/' + p for p in ['site.css', 'theme.css', 'salon.css', 'pwa.css',
             'player-screen.css', 'mark.svg', 'theme.js', 'storage.js', 'site.js',
             'catalog.js', 'salon.js', 'salon-day.js', 'auth.js', 'play.js', 'pwa.js',
             'information.css', 'rules.js']]
    digest = hashlib.sha256(json.dumps(dict(files=files, core=sorted(set(core))), sort_keys=True).encode())
    for name in files + ['service-worker.js']:
        digest.update(name.encode() + b'\0' + (ROOT / name).read_bytes())
    pack = dict(version=digest.hexdigest()[:20], files=files, core=sorted(set(core)),
                games=len(games), bytes=sum((ROOT / name).stat().st_size for name in files))
    return '// Generated by scripts/build_offline_pack.py; do not edit.\nself.SpinnerOfflinePack = ' + json.dumps(pack, ensure_ascii=False, indent=2) + ';\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    result = build()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != result:
            raise SystemExit('Offline pack is stale. Run python3 scripts/build_offline_pack.py')
        print('Offline pack is current.')
    else:
        OUTPUT.write_text(result)
        print('Generated public offline pack.')
